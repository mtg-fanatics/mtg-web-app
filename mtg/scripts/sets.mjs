// Writes lib/sets.ts: the sets the library's "Set" filter and set-code search know (code, name, release year, whether Standard legal), newest first.
// Names and dates come from Scryfall's list of sets; "Standard legal" from the cached oracle cards (import:cards downloads them).
// Run from the mtg folder (again after a rotation):   node scripts/sets.mjs
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";

const CACHE = path.resolve(".import-cache");
const file = fs.readdirSync(CACHE).filter((f) => f.startsWith("oracle-cards") && f.endsWith(".jsonl.gz")).sort().pop();
const KINDS = new Set(["core", "expansion", "masters", "draft_innovation", "commander", "starter", "funny", "box", "eternal", "arsenal", "duel_deck", "from_the_vault", "spellbook", "premium_deck", "planechase", "archenemy", "memorabilia"]);

// how many Standard-legal cards each core or expansion set has as the newest printing (a few legal reprints do not make an old set Standard)
const legal = new Map();
for (const line of zlib.gunzipSync(fs.readFileSync(path.join(CACHE, file))).toString("utf8").split("\n")) {
  if (!line.trim()) continue;
  const c = JSON.parse(line);
  if (c.legalities?.standard === "legal" && (c.set_type === "core" || c.set_type === "expansion")) legal.set(c.set, (legal.get(c.set) ?? 0) + 1);
}

const res = await fetch("https://api.scryfall.com/sets", { headers: { "User-Agent": "MTGDuelPersonalProject/0.1 (personal, non-commercial)", Accept: "application/json" } });
if (!res.ok) throw new Error(`Scryfall said ${res.status}`);
const { data } = await res.json();
const list = data
  .filter((s) => !s.digital && KINDS.has(s.set_type) && s.released_at)
  .map((s) => ({ code: s.code, name: s.name, released: s.released_at, standard: (s.set_type === "core" || s.set_type === "expansion") && (legal.get(s.code) ?? 0) >= 15 }))
  .sort((a, b) => (a.released < b.released ? 1 : a.released > b.released ? -1 : a.name.localeCompare(b.name)));
const rows = list.map((s) => `  { code: ${JSON.stringify(s.code)}, name: ${JSON.stringify(s.name)}, year: ${Number(s.released.slice(0, 4))}${s.standard ? ", standard: true" : ""} },`).join("\n");
fs.writeFileSync(path.join("lib", "sets.ts"), `// Generated by scripts/sets.mjs: the sets the library's Set filter and set-code search know, newest first.\nexport interface CardSet {\n  code: string;\n  name: string;\n  year: number;\n  /** Legal in Standard today (a core or expansion set with Standard-legal cards). */\n  standard?: boolean;\n}\n\nexport const CARD_SETS: CardSet[] = [\n${rows}\n];\n`);
console.log(`${list.length} sets written to lib/sets.ts (${list.filter((s) => s.standard).length} Standard legal)`);
