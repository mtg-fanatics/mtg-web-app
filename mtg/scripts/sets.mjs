// Writes lib/sets.ts: the sets the library's "Set" filter offers (code, name, release year), newest first.
// Run from the mtg folder after the oracle cards are cached:   node scripts/sets.mjs
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";

const CACHE = path.resolve(".import-cache");
const file = fs.readdirSync(CACHE).filter((f) => f.startsWith("oracle-cards") && f.endsWith(".jsonl.gz")).sort().pop();
const KINDS = new Set(["core", "expansion", "masters", "draft_innovation", "commander"]);
const sets = new Map();
for (const line of zlib.gunzipSync(fs.readFileSync(path.join(CACHE, file))).toString("utf8").split("\n")) {
  if (!line.trim()) continue;
  const c = JSON.parse(line);
  if (!KINDS.has(c.set_type)) continue;
  const s = sets.get(c.set) ?? { code: c.set, name: c.set_name, released: c.released_at, kind: c.set_type };
  if (c.released_at < s.released) s.released = c.released_at; // the set came out with its first card
  sets.set(c.set, s);
}
const list = [...sets.values()].sort((a, b) => (a.released < b.released ? 1 : a.released > b.released ? -1 : a.name.localeCompare(b.name)));
const rows = list.map((s) => `  { code: ${JSON.stringify(s.code)}, name: ${JSON.stringify(s.name)}, year: ${Number(s.released.slice(0, 4))} },`).join("\n");
fs.writeFileSync(path.join("lib", "sets.ts"), `// Generated by scripts/sets.mjs: the sets the library's Set filter offers, newest first.\nexport interface CardSet {\n  code: string;\n  name: string;\n  year: number;\n}\n\nexport const CARD_SETS: CardSet[] = [\n${rows}\n];\n`);
console.log(`${list.length} sets written to lib/sets.ts`);
